import PDFDocument from "pdfkit"

const generatepdf = async (data: any) => {
  return new Promise((resolve, reject) => {
    const doc = new PDFDocument({
      size: "A4",
      margin: 50,
      info: {
        Author: "Gothalo AI",
        Title: data.title,
        Creator: "Gothalo AI"
      }
    })

    const chunks: any = []
    doc.on("data", (chunk) => {
      chunks.push(chunk)
    })
    doc.on("end", () => {
      resolve(Buffer.concat(chunks))
    })
    doc.on("error", () => reject())

    doc.fillColor("#111827").fontSize(28).text(data.title)

    if (data.subtitle) {
      doc.moveDown(0.5)
    }

    doc.fillColor("#9CA3AF").fontSize(12).text(data.subtitle, {
      align: "center"
    })

    doc.moveDown(2)

    data.sections.forEach((element: any) => {
      doc.fillColor("#4F46E5").fontSize(18).text(element.heading)

      doc.moveDown(0.5)

      element.points.forEach((elem: any) => {
        doc
          .fillColor("#4F46E5")
          .fontSize(12)
          .text("• ", { continued: true, lineGap: 5 })
        doc
          .fillColor("#111827")
          .fontSize(12)
          .text(elem, { lineGap: 5 })
      });
      doc.moveDown()
    });
    doc.moveDown()

    doc.fillColor("#9CA3AF").fontSize(10).text("Generated by Gothalo AI", {
      align: "center"
    })

    doc.end()
  })
}
export { generatepdf }