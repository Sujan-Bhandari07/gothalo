
import PDFDocument from "pdfkit"
const generatepdf=async(data:any)=>{
return new Promise((resolve,reject)=>{
const doc =new PDFDocument({
    size:"A4",
    margin:50,info:{
        Author:"Gothalo AI",
        Title:data.title,
        Creator:"Gothalo AI"
    }
})
const chunks:any=[]
doc.on("data",(chunk)=>{
chunks.push(chunk)
})
doc.on("end",()=>{
    resolve(Buffer.concat(chunks))
})
doc.on("error",()=>reject())
doc.fontSize(28)
.text(data.title).fillColor("#111827")

if(data.subtitle){
   doc.moveDown(0.5)
}

doc.fontSize(12)
.text(data.subtitle,{
    align:"center"

}).fillColor("#6B7280")

doc.moveDown(2)

data.sections.forEach((element:any) => {
    doc.fontSize(18).text(element.heading
    ).fillColor("#111827")

doc.moveDown(0.5)

element.points.forEach((elem:any) => {
    doc.fontSize(12).text("• "+elem,{
lineGap:5
    }).fillColor("#374151")
});
doc.moveDown()
});
doc.moveDown()

doc.fontSize(10)
.text("Generated by Gothalo AI",{
    align:"center"
}).fillColor("#9CA3AF")

doc.end()
})
}
export{generatepdf}