import PptxGenJS from "pptxgenjs";

const COLORS = {
  primary: "4F46E5",
  primaryDark: "3730A3",
  accent: "818CF8",
  secondary: "0F172A",
  text: "334155",
  light: "F8FAFC",
  card: "EEF2FF",
  border: "E2E8F0",
  white: "FFFFFF",
  muted: "94A3B8",
};

const generateppt = async (data: any): Promise<Buffer> => {
  try {
    const ppt = new (PptxGenJS as any)();
    ppt.layout = "LAYOUT_WIDE";
    ppt.title = data.title;
    ppt.author = "Gothalo AI";
    ppt.subject = data.title;
    ppt.company = "Gothalo AI";
    ppt.theme = {
      headFontFace: "Aptos",
      bodyFontFace: "Aptos",
    };

    addcover(ppt, data);
    data.slides.forEach((s: any, i: number) => {
      addslide(ppt, s.title, s.points, i + 1, data.slides.length);
    });
    addthankyou(ppt);

    const buffer = (await ppt.write({
      outputType: "nodebuffer",
    })) as Buffer;

    return buffer;
  } catch (error: any) {
    console.error("generateppt failed:", error);
    throw error;
  }
};

const addcover = (ppt: any, data: any) => {
  const slide = ppt.addSlide();
  slide.background = { color: COLORS.secondary };

  // decorative accent circles (top-right cluster)
  slide.addShape(ppt.ShapeType.ellipse, {
    x: 10.6,
    y: -1.2,
    w: 4.5,
    h: 4.5,
    fill: { color: COLORS.primary, transparency: 60 },
    line: { type: "none" },
  });
  slide.addShape(ppt.ShapeType.ellipse, {
    x: 11.8,
    y: 0.3,
    w: 2.2,
    h: 2.2,
    fill: { color: COLORS.accent, transparency: 40 },
    line: { type: "none" },
  });

  // bottom accent bar
  slide.addShape(ppt.ShapeType.rect, {
    x: 0,
    y: 7.32,
    w: 13.33,
    h: 0.11,
    fill: { color: COLORS.primary },
    line: { type: "none" },
  });

  // small kicker label above title
  slide.addShape(ppt.ShapeType.roundRect, {
    x: 0.7,
    y: 2.55,
    w: 2.1,
    h: 0.4,
    fill: { color: COLORS.primary },
    line: { type: "none" },
    rectRadius: 0.2,
  });
  slide.addText("PRESENTATION", {
    x: 0.7,
    y: 2.55,
    w: 2.1,
    h: 0.4,
    align: "center",
    valign: "middle",
    color: COLORS.white,
    bold: true,
    fontSize: 10,
    charSpacing: 1,
  });

  slide.addText(data.title, {
    x: 0.7,
    y: 3.1,
    w: 11.5,
    h: 1.3,
    align: "left",
    color: COLORS.white,
    bold: true,
    fontSize: 38,
  });

  if (data.subtitle) {
    slide.addText(data.subtitle, {
      x: 0.7,
      y: 4.35,
      w: 10.5,
      h: 0.6,
      align: "left",
      color: "CBD5E1",
      fontSize: 16,
    });
  }

  slide.addText("Generated by Gothalo AI", {
    x: 0.7,
    y: 6.85,
    w: 6,
    h: 0.3,
    align: "left",
    color: COLORS.muted,
    fontSize: 11,
  });
};

const addslide = (
  ppt: any,
  title: string,
  points: any,
  page: number,
  total: number
) => {
  const slide = ppt.addSlide();
  slide.background = { color: COLORS.white };

  // slide number badge, top-left
  slide.addShape(ppt.ShapeType.roundRect, {
    x: 0.6,
    y: 0.4,
    w: 0.55,
    h: 0.55,
    fill: { color: COLORS.card },
    line: { color: COLORS.border, width: 1 },
    rectRadius: 0.1,
  });
  slide.addText(String(page).padStart(2, "0"), {
    x: 0.6,
    y: 0.4,
    w: 0.55,
    h: 0.55,
    align: "center",
    valign: "middle",
    color: COLORS.primary,
    bold: true,
    fontSize: 13,
  });

  slide.addText(title, {
    x: 1.35,
    y: 0.38,
    w: 10.5,
    h: 0.6,
    valign: "middle",
    color: COLORS.secondary,
    bold: true,
    fontSize: 24,
  });

  // accent underline (short, colored — not full width)
  slide.addShape(ppt.ShapeType.rect, {
    x: 1.37,
    y: 1.0,
    w: 1.4,
    h: 0.05,
    fill: { color: COLORS.primary },
    line: { type: "none" },
  });

  const vpoints = points.slice(0, 6);
  const startY = 1.4;
  const rowH = 0.85;

  vpoints.forEach((p: any, i: number) => {
    const y = startY + i * rowH;

    // card background
    slide.addShape(ppt.ShapeType.roundRect, {
      x: 0.7,
      y,
      w: 11.9,
      h: 0.68,
      fill: { color: i % 2 ? COLORS.light : COLORS.white },
      line: { color: COLORS.border, width: 0.75 },
      rectRadius: 0.06,
    });

    // numbered circle badge instead of a plain dot
    slide.addShape(ppt.ShapeType.ellipse, {
      x: 0.9,
      y: y + 0.14,
      w: 0.4,
      h: 0.4,
      fill: { color: COLORS.primary },
      line: { type: "none" },
    });
    slide.addText(String(i + 1), {
      x: 0.9,
      y: y + 0.14,
      w: 0.4,
      h: 0.4,
      align: "center",
      valign: "middle",
      color: COLORS.white,
      bold: true,
      fontSize: 12,
    });

    slide.addText(p, {
      x: 1.5,
      y: y + 0.05,
      w: 10.9,
      h: 0.58,
      valign: "middle",
      fit: "shrink",
      color: COLORS.text,
      fontSize: 14.5,
    });
  });

  // footer: brand + progress bar + page count
  slide.addText("Gothalo AI", {
    x: 0.6,
    y: 6.95,
    w: 2,
    h: 0.25,
    fontSize: 9.5,
    color: COLORS.muted,
  });

  // progress bar track
  slide.addShape(ppt.ShapeType.rect, {
    x: 4.5,
    y: 7.08,
    w: 4.3,
    h: 0.05,
    fill: { color: COLORS.border },
    line: { type: "none" },
  });
  // progress bar fill
  slide.addShape(ppt.ShapeType.rect, {
    x: 4.5,
    y: 7.08,
    w: 4.3 * (page / total),
    h: 0.05,
    fill: { color: COLORS.primary },
    line: { type: "none" },
  });

  slide.addText(`${page} / ${total}`, {
    x: 11.3,
    y: 6.95,
    w: 1.4,
    h: 0.25,
    align: "right",
    fontSize: 9.5,
    color: COLORS.muted,
  });
};

const addthankyou = (ppt: any) => {
  const slide = ppt.addSlide();
  slide.background = { color: COLORS.secondary };

  slide.addShape(ppt.ShapeType.ellipse, {
    x: -1.5,
    y: 4.5,
    w: 4,
    h: 4,
    fill: { color: COLORS.primary, transparency: 55 },
    line: { type: "none" },
  });
  slide.addShape(ppt.ShapeType.ellipse, {
    x: 10.8,
    y: -1.5,
    w: 4,
    h: 4,
    fill: { color: COLORS.accent, transparency: 55 },
    line: { type: "none" },
  });

  slide.addText("Thank You", {
    x: 0,
    y: 3.0,
    w: 13.33,
    h: 0.9,
    align: "center",
    color: COLORS.white,
    fontSize: 40,
    bold: true,
  });

  slide.addShape(ppt.ShapeType.rect, {
    x: 6.16,
    y: 3.95,
    w: 1,
    h: 0.05,
    fill: { color: COLORS.primary },
    line: { type: "none" },
  });

  slide.addText("Generated by Gothalo AI", {
    x: 0,
    y: 6.9,
    w: 13.33,
    h: 0.3,
    align: "center",
    color: COLORS.muted,
    fontSize: 13,
  });
};

export { generateppt };